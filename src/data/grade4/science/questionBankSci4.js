export const getQuestionsByWeekSci4 = (weekNum) => {
  const num = parseInt(weekNum, 10);
  return QUESTION_BANK_SCI4.filter(q => q.week === num);
};

export const getFilteredQuestionsSci4 = ({ semester, stage, category, difficulty, count = 10 }) => {
  let list = [...QUESTION_BANK_SCI4];
  if (semester && semester !== 'all') {
    list = list.filter(q => q.semester === parseInt(semester, 10));
  }
  if (stage && stage !== 'all') {
    list = list.filter(q => q.stage === parseInt(stage, 10));
  }
  if (category && category !== 'all') {
    list = list.filter(q => q.category === category);
  }
  if (difficulty && difficulty !== 'all') {
    list = list.filter(q => q.difficulty === difficulty);
  }
  return list.slice(0, count);
};
