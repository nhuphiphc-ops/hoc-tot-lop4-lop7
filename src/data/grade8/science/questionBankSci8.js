export const getQuestionsByWeekSci8 = (week) => {
  return QUESTION_BANK_SCI8.filter(q => q.week === parseInt(week));
};

export const getFilteredQuestionsSci8 = ({ category, week }) => {
  let filtered = QUESTION_BANK_SCI8;
  if (category && category !== 'all') {
    filtered = filtered.filter(q => q.category === category);
  }
  if (week) {
    filtered = filtered.filter(q => q.week === parseInt(week));
  }
  return filtered;
};
