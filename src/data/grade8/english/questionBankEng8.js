export const getFilteredQuestionsEng8 = ({ week, semester, stage, difficulty, category } = {}) => {
  return QUESTION_BANK_ENG8.filter(q => {
    if (week && week !== 'all' && q.week !== Number(week)) return false;
    if (semester && semester !== 'all' && q.semester !== Number(semester)) return false;
    if (stage && stage !== 'all' && q.stage !== Number(stage)) return false;
    if (difficulty && difficulty !== 'all' && q.difficulty !== difficulty) return false;
    if (category && category !== 'all' && q.category !== category) return false;
    return true;
  });
};
